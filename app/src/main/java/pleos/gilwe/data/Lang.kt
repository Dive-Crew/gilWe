enum class Lang(val code: String, val label: String, val locale: Locale) {
    EN("EN", "English", Locale.US),
    KO("KO", "한국어", Locale.KOREA),
    JA("JA", "日本語", Locale.JAPAN),
    ZH("ZH", "中文", Locale.CHINA),
    VI("VI", "Tiếng Việt", Locale("vi", "VN")),
    TH("TH", "ไทย", Locale("th", "TH"));

    val strings: S get() = if (this == KO) S.KO else S.EN
    /** 이야기 본문은 한국어/영어 두 벌. 한국어가 아니면 영어 원고를 쓴다. */
    val isKorean: Boolean get() = this == KO
}

